export function getProjectsByPlacement(placement: ProjectPlacement) {
  return projectCatalog
    .filter(
      (project) =>
        project.placement === placement &&
        project.portfolioVisibility === "visible",
    )
    .sort((a, b) => a.order - b.order);
}

export function getProjectBySlug(slug: string) {
  return projectCatalog.find((project) => project.slug === slug);
}

export function getProjectById(id: ProjectId) {
  return projectCatalog.find((project) => project.id === id);
}
